-- 3) 게시판 권한
-- 배열이 빈 경우 전체 승인 직원에게 허용
-- ---------------------------------------------------------------------
create table if not exists public.board_permissions (
  board_type text primary key
    check (board_type in ('notice','project','webzine','files','gallery')),
  read_departments text[] not null default '{}',
  write_departments text[] not null default '{}',
  updated_by uuid references public.profiles(id) on delete set null,
  updated_at timestamptz not null default now()
);

insert into public.board_permissions (board_type)
values ('notice'),('project'),('webzine'),('files'),('gallery')
on conflict (board_type) do nothing;

create or replace function public.can_read_board(p_board_type text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    public.is_admin()
    or (
      public.is_approved()
      and exists (
        select 1
        from public.board_permissions bp
        where bp.board_type = p_board_type
          and (
            cardinality(bp.read_departments) = 0
            or public.current_department() = any(bp.read_departments)
          )
      )
    );
$$;

create or replace function public.can_write_board(p_board_type text)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select
    public.is_admin()
    or (
      public.is_approved()
      and exists (
        select 1
        from public.board_permissions bp
        where bp.board_type = p_board_type
          and (
            cardinality(bp.write_departments) = 0
            or public.current_department() = any(bp.write_departments)
          )
      )
    );
$$;


