  public.can_write_board(board_type)
  and (
    author_id = (select auth.uid())
    or public.is_admin()
  )
);

-- 일반 작성자가 is_pinned을 바꾸지 못하도록 Trigger
create or replace function public.protect_post_admin_fields()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    new.is_pinned := old.is_pinned;
    new.view_count := old.view_count;
    new.author_id := old.author_id;
    new.board_type := old.board_type;
  end if;
  return new;
end;
$$;

drop trigger if exists protect_post_admin_fields_trigger on public.posts;
create trigger protect_post_admin_fields_trigger
before update on public.posts
for each row execute procedure public.protect_post_admin_fields();

drop policy if exists "Authors or admins delete posts" on public.posts;
create policy "Authors or admins delete posts"
on public.posts
for delete
to authenticated
using (
  author_id = (select auth.uid())
  or public.is_admin()
);


