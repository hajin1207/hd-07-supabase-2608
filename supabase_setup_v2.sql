drop policy if exists "Users read own profile" on public.profiles;
create policy "Users read own profile"
on public.profiles
for select
to authenticated
using (
  id = (select auth.uid())
  or public.is_admin()
  or (public.is_approved() and approved = true)
);

drop policy if exists "Admins manage profiles" on public.profiles;
create policy "Admins manage profiles"
on public.profiles
for update
to authenticated
using (
  public.is_admin()
  or id = (select auth.uid())
)
with check (
  public.is_admin()
  or (
    id = (select auth.uid())
    -- 사용자는 자신의 role/approved를 임의 변경할 수 없어야 함.
    -- 아래 Trigger에서 민감 컬럼을 보호함.
  )
);

-- 일반 사용자의 role/approved 변경 방지
create or replace function public.protect_profile_privileges()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  if auth.uid() = old.id and not public.is_admin() then
    new.role := old.role;
    new.approved := old.approved;
  end if;
  return new;
end;
$$;

drop trigger if exists protect_profile_privileges_trigger on public.profiles;
create trigger protect_profile_privileges_trigger
before update on public.profiles
for each row execute procedure public.protect_profile_privileges();


