-- 9) 조회수 RPC
-- 승인된 사용자가 볼 수 있는 게시글만 +1
-- ---------------------------------------------------------------------
create or replace function public.increment_post_view(p_post_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_board_type text;
begin
  select board_type into v_board_type
  from public.posts
  where id = p_post_id;

  if v_board_type is null then
    return;
  end if;

  if not public.can_read_board(v_board_type) then
    raise exception 'not authorized';
  end if;

  update public.posts
  set view_count = view_count + 1
  where id = p_post_id;
end;
$$;

revoke all on function public.increment_post_view(bigint) from public;
grant execute on function public.increment_post_view(bigint) to authenticated;


