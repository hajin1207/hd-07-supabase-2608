-- 2) 보안 Helper Functions
-- security definer 함수로 RLS 내부의 반복 조회를 단순화
-- ---------------------------------------------------------------------
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.role = 'admin'
      and p.approved = true
  );
$$;

create or replace function public.is_approved()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles p
    where p.id = auth.uid()
      and p.approved = true
  );
$$;

create or replace function public.current_department()
returns text
language sql
stable
security definer
set search_path = ''
as $$
  select p.department
  from public.profiles p
  where p.id = auth.uid()
  limit 1;
$$;


